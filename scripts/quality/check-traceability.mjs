#!/usr/bin/env node
// Business traceability gate.
// Reads the business rules (BR-...) and acceptance criteria (AC-...) declared
// in docs/features/*.md, finds which test files cite each AC, writes the
// matrix to docs/testing/traceability-matrix.md and fails when:
//   - a BR has no AC,
//   - an AC points to an unknown BR,
//   - an AC is cited by no test,
//   - a test cites an AC that does not exist.
// Usage: node scripts/quality/check-traceability.mjs [--check]
//   --check  do not rewrite the matrix, fail if the committed one is stale
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const FEATURES = path.join(root, "docs/features");
const TEST_DIRS = ["test", "cypress"].map(function (d) {
  return path.join(root, d);
});
const MATRIX = path.join(root, "docs/testing/traceability-matrix.md");
const TEST_FILE = /\.(test|spec|cy)\.(m?js|jsx|ts|tsx)$|\/performance\/k6\/.+\.js$/;
// "tooling" holds the tests of this script: they cite sample IDs (AC-X-01...)
// on purpose and are not tests of the product.
const SKIP_DIRS = new Set(["node_modules", "test-results", "screenshots", "videos", "fixtures", "tooling"]);

const ID = "[A-Z]+(?:-[A-Z]+)*-\\d{2,3}";
const BR_ROW = new RegExp("^\\|\\s*(BR-" + ID + ")\\s*\\|\\s*([^|]+?)\\s*\\|\\s*$");
const AC_ROW = new RegExp("^\\|\\s*(AC-" + ID + ")\\s*\\|\\s*(BR-" + ID + ")\\s*\\|\\s*([^|]+?)\\s*\\|");
const AC_CITE = new RegExp("\\bAC-" + ID + "\\b", "g");

export function parseFeature(text, file) {
  const brs = [];
  const acs = [];
  text.split(/\r?\n/).forEach(function (line) {
    let m = AC_ROW.exec(line);
    if (m) {
      acs.push({ id: m[1], br: m[2], text: m[3], file: file });
      return;
    }
    m = BR_ROW.exec(line);
    if (m) {
      brs.push({ id: m[1], text: m[2], file: file });
    }
  });
  return { brs: brs, acs: acs };
}

function walk(dir, out) {
  if (!existsSync(dir)) {
    return out;
  }
  readdirSync(dir).forEach(function (name) {
    if (SKIP_DIRS.has(name)) {
      return;
    }
    const full = path.join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      walk(full, out);
    } else if (TEST_FILE.test(full)) {
      out.push(full);
    }
  });
  return out;
}

export function analyse(features, tests) {
  const brs = new Map();
  const acs = new Map();
  const errors = [];
  features.forEach(function (f) {
    f.brs.forEach(function (b) {
      if (brs.has(b.id)) {
        errors.push("duplicate " + b.id + " in " + b.file + " and " + brs.get(b.id).file);
      }
      brs.set(b.id, b);
    });
    f.acs.forEach(function (a) {
      if (acs.has(a.id)) {
        errors.push("duplicate " + a.id + " in " + a.file + " and " + acs.get(a.id).file);
      }
      acs.set(a.id, Object.assign({ tests: [] }, a));
    });
  });
  acs.forEach(function (a) {
    if (!brs.has(a.br)) {
      errors.push(a.id + " points to unknown " + a.br + " (" + a.file + ")");
    }
  });
  brs.forEach(function (b) {
    const has = Array.from(acs.values()).some(function (a) {
      return a.br === b.id;
    });
    if (!has) {
      errors.push(b.id + " has no acceptance criterion (" + b.file + ")");
    }
  });
  const untagged = [];
  tests.forEach(function (t) {
    const cited = new Set(t.text.match(AC_CITE) || []);
    if (cited.size === 0) {
      untagged.push(t.file);
    }
    cited.forEach(function (id) {
      if (!acs.has(id)) {
        errors.push(t.file + " cites unknown " + id);
      } else {
        acs.get(id).tests.push(t.file);
      }
    });
  });
  acs.forEach(function (a) {
    if (a.tests.length === 0) {
      errors.push(a.id + " is not covered by any test (" + a.file + ")");
    }
  });
  return { brs: brs, acs: acs, errors: errors, untagged: untagged };
}

function level(file) {
  if (/performance\/k6/.test(file)) return "performance";
  if (/^cypress\/|\/e2e\//.test(file)) return "E2E";
  if (/\/acceptance\//.test(file)) return "acceptance";
  if (/\/non-functional\//.test(file)) return "non-functional";
  if (/\/functional\//.test(file)) return "integration";
  if (/\/unit\//.test(file)) return "unit";
  return "other";
}

export function renderMatrix(result) {
  const lines = [
    "# Traceability matrix: business rules, acceptance criteria, tests",
    "",
    "Generated by `node scripts/quality/check-traceability.mjs`. Do not edit by hand:",
    "change the feature docs in `docs/features/` or the `Couvre :` line of a test.",
    "",
    "| BR | AC | Criterion | Levels | Tests |",
    "|---|---|---|---|---|",
  ];
  const ordered = Array.from(result.acs.values()).sort(function (a, b) {
    return a.br.localeCompare(b.br) || a.id.localeCompare(b.id, undefined, { numeric: true });
  });
  ordered.forEach(function (a) {
    const levels = Array.from(new Set(a.tests.map(level))).sort().join(", ");
    const tests = a.tests
      .slice()
      .sort()
      .map(function (t) {
        return "`" + t + "`";
      })
      .join("<br>");
    lines.push("| " + a.br + " | " + a.id + " | " + a.text.replace(/\|/g, "/") + " | " + (levels || "none") + " | " + (tests || "**none**") + " |");
  });
  lines.push("");
  lines.push("Summary: " + result.brs.size + " business rules, " + result.acs.size + " acceptance criteria, " +
    ordered.filter(function (a) { return a.tests.length > 0; }).length + " covered.");
  if (result.untagged.length > 0) {
    lines.push("");
    lines.push("Test files that cite no AC (technical tests, allowed but listed):");
    lines.push("");
    result.untagged.sort().forEach(function (f) {
      lines.push("- `" + f + "`");
    });
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const features = readdirSync(FEATURES)
    .filter(function (f) {
      return f.endsWith(".md");
    })
    .map(function (f) {
      return parseFeature(readFileSync(path.join(FEATURES, f), "utf8"), "docs/features/" + f);
    });
  const tests = [];
  TEST_DIRS.forEach(function (d) {
    walk(d, []).forEach(function (full) {
      tests.push({ file: path.relative(root, full), text: readFileSync(full, "utf8") });
    });
  });
  const result = analyse(features, tests);
  const matrix = renderMatrix(result);
  if (check) {
    const current = existsSync(MATRIX) ? readFileSync(MATRIX, "utf8") : "";
    if (current !== matrix) {
      result.errors.push("docs/testing/traceability-matrix.md is stale, run: npm run quality:traceability");
    }
  } else {
    writeFileSync(MATRIX, matrix);
  }
  console.log("traceability: " + result.brs.size + " BR, " + result.acs.size + " AC, " + tests.length + " test files, " + result.untagged.length + " without AC");
  if (result.errors.length > 0) {
    result.errors.forEach(function (e) {
      console.error("  FAIL " + e);
    });
    process.exit(1);
  }
  console.log("traceability: OK");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
